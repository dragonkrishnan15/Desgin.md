// Validate all palettes meet WCAG AA (contrast >= 4.5 between bg and text)
export function validatePalettes(): { valid: boolean; failures: string[] } {
  const failures: string[] = [];
  for (const pal of PALETTES) {
    const bgTextRatio = contrast(pal.bg, pal.text);
    if (bgTextRatio < 4.5) {
      failures.push(`${pal.name} (${pal.id}): bg ${pal.bg} vs text ${pal.text} = ${bgTextRatio} (requires >= 4.5)`);
    }
  }
  return {
    valid: failures.length === 0,
    failures,
  };
}

